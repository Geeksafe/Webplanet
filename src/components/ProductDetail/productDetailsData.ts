export const getProductDetailById = (productId: string): ProductDetail => {
  if (productDetailsMap[productId]) {
    return productDetailsMap[productId];
  }

  // Fallback to finding from allProducts
  const baseProduct = allProducts.find((p) => p.id === productId) || allProducts[0];
  if (productDetailsMap[baseProduct.id]) {
    return productDetailsMap[baseProduct.id];
  }

  // Default fallback
  return {
    ...baseProduct,
    sku: 'HP-DEFAULT',
    tag: baseProduct.title,
    freeShipping: true,
    gallery: [baseProduct.image],
    features: [
      {
        title: 'High Reliability Printing',
        description: 'Engineered for seamless everyday performance with sharp text and vibrant color.',
      },
    ],
    specifications: [
      { category: 'Product', value: baseProduct.title },
      { category: 'Category', value: baseProduct.category },
      { category: 'Warranty', value: 'One-year limited hardware warranty' },
    ],
  };
};

export const getRelatedProducts = (currentProductId: string, count = 3) => {
  const current = allProducts.find((p) => p.id === currentProductId);
  const others = allProducts.filter((p) => p.id !== currentProductId);

  if (current) {
    const sameCategory = others.filter((p) => p.category === current.category);
    if (sameCategory.length >= count) {
      return sameCategory.slice(0, count);
    }
  }

  return others.slice(0, count);
};
